#define SET_TIME_MS     (10000U)        /* fixed for now: 10.0 s */

/* Show a 0..999 value on three digits starting at first_digit */
static void show_3digits(U8 first_digit, U16 value)
{
    display_set_number(first_digit,      (U8) ((value / 100U) % 10U));
    display_set_number(first_digit + 1U, (U8) ((value / 10U) % 10U));
    display_set_number(first_digit + 2U, (U8) (value % 10U));
}

typedef enum
{
    UI_RUN = 0,         /* normal operation                         */
    UI_SET              /* editing the set value on the bottom row  */
} ui_mode_t;

#define BLINK_HALF_MS   (250U)          /* edited digit: 250 ms on / 250 ms off */

/* Bottom row in SET mode: three digits, the one at blink_pos blanked when blank_now = 1 */
static void show_set_value(U16 value, U8 blink_pos, U8 blank_now)
{
    U8 d[3];

    d[0] = (U8) ((value / 100U) % 10U);
    d[1] = (U8) ((value / 10U) % 10U);
    d[2] = (U8) (value % 10U);

    for (U8 i = 0; i < 3U; i++)
    {
        if (blank_now && (i == blink_pos))
        {
            display_blank_digit((U8) (3U + i));
        }
        else
        {
            display_set_number((U8) (3U + i), d[i]);
        }
    }
}

/* Change one decimal digit of value (pos 0 = hundreds, 1 = tens, 2 = units), wrapping 0..9 */
static U16 change_digit(U16 value, U8 pos, U8 up)
{
    U16 weight    = (0U == pos) ? 100U : ((1U == pos) ? 10U : 1U);
    U8  digit     = (U8) ((value / weight) % 10U);
    U8  new_digit = up ? (U8) ((digit + 1U) % 10U)      /* 9 -> 0 */
                       : (U8) ((digit + 9U) % 10U);     /* 0 -> 9 */

    return (U16) (value - (U16) (digit * weight) + (U16) (new_digit * weight));
}

/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/

void hal_entry(void)
{
    U16 last_start;

    ui_mode_t ui_mode    = UI_RUN;
    U16       edit_value = 0;       /* set value being edited, in 0.1 s units */
    U8        edit_pos   = 0;       /* 0..2 = which bottom-row digit is edited */

    relay_init();
    display_init();
    key_init();
    din_init();
    tmr_init(SET_TIME_MS);

    R_TAU_Open(&g_timer_1ms_ctrl, &g_timer_1ms_cfg);
    R_TAU_Start(&g_timer_1ms_ctrl);

    R_ICU_ExternalIrqOpen(&g_start_irq_ctrl, &g_start_irq_cfg);
    R_ICU_ExternalIrqEnable(&g_start_irq_ctrl);

    display_set_dp(1, 1);       /* top row    "10.0" : DP after the 2nd digit */
    display_set_dp(4, 1);       /* bottom row "10.0" */

    last_start = din_get_start_count();

    while (1)
    {
        /* ---- 0. Keys -> UI mode ---- */
        key_event_t evt = key_get_event();
        if (UI_RUN == ui_mode)
        {
            if (KEY_EVT_SET_LONG == evt)                            /* SET held 3 s: enter SET mode */
            {
                edit_value = (U16) (tmr_get_set_ms() / 100U);
                edit_pos   = 0;
                ui_mode    = UI_SET;
            }
        }
        else    /* UI_SET */
        {
            if (KEY_EVT_SET_LONG == evt)                            /* 5c-1: exit, no save yet */
            {
                ui_mode = UI_RUN;
            }
            else if (KEY_EVT_UP_SHORT == evt)                       /* UP: digit + 1 */
            {
                edit_value = change_digit(edit_value, edit_pos, 1U);
            }
            else if (KEY_EVT_DOWN_SHORT == evt)                     /* DOWN: digit - 1 */
            {
                edit_value = change_digit(edit_value, edit_pos, 0U);
            }
            else if (KEY_EVT_SET_SHORT == evt)                      /* SET tap: next digit */
            {
                edit_pos = (U8) ((edit_pos + 1U) % 3U);
            }
        }

        /* ---- 1. Inputs -> timer requests ---- */
        U16 now_start = din_get_start_count();

        if (din_reset_active())
        {
            tmr_reset();
        }
        else if (now_start != last_start)
        {
            tmr_start();
        }
        last_start = now_start;

        /* ---- 2. Timer state -> relays (On Delay: ON after set time) ---- */
        tmr_state_t st = tmr_get_state();

        if (TMR_DONE == st)
        {
            relay_on(RELAY_1);
            relay_on(RELAY_2);
        }
        else
        {
            relay_off(RELAY_1);
            relay_off(RELAY_2);
        }

        /* ---- 3. Front-panel LEDs (CC7) ---- */
        U8 leds = 0;
        if (relay_is_on(RELAY_1)) { leds |= LED_OUT1; }
        if (relay_is_on(RELAY_2)) { leds |= LED_OUT2; }

        if (TMR_RUNNING == st)
        {
            if (((tmr_get_elapsed_ms() / 500U) % 2U) == 0U)
            {
                leds |= LED_S;              /* blink: on for 500 ms, off for 500 ms */
            }
        }
        else
        {
            leds |= LED_S;                  /* steady when idle or done */
        }

        display_set_leds(leds);

        /* ---- 4. Display (in 0.1 s units, DP comes in step 5b) ---- */
        U32 remaining_ms = tmr_get_set_ms() - tmr_get_elapsed_ms();
        U16 remaining_01 = (U16) ((remaining_ms + 99U) / 100U);   /* round up */

        show_3digits(0, remaining_01);                                      /* top: time left   */
//        show_3digits(3, (U16) (tmr_get_set_ms() / 100U));              /* bottom: set time */
        if (UI_SET == ui_mode)
        {
            U8 blank_now = (U8) (((tick_get_ms() / BLINK_HALF_MS) % 2U) == 0U);
            show_set_value(edit_value, edit_pos, blank_now);        /* bottom: value being edited */
        }
        else
        {
            show_3digits(3, (U16) (tmr_get_set_ms() / 100U));      /* bottom: set time */
        }
    }
}

