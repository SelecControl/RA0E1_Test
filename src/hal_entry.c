/*
 * BASELINE TEST (display, relays)
 *
 *   Top row    : key event
 *   Bottom row : which key is pressed
 *   Relays     : both OFF (initialised only)
 */

/* Show a 0..999 value on three digits starting at first_digit (leading zero blanked) */
static void show_3digits(U8 first_digit, U16 value)
{
    if ((value / 100U) == 0U)
    {
        display_blank_digit(first_digit);
    }
    else
    {
        display_set_number(first_digit, (U8) ((value / 100U) % 10U));
    }
    display_set_number(first_digit + 1U, (U8) ((value / 10U) % 10U));
    display_set_number(first_digit + 2U, (U8) (value % 10U));
}

/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    relay_init();
    display_init();

    R_TAU_Open(&g_timer_1ms_ctrl, &g_timer_1ms_cfg);
    R_TAU_Start(&g_timer_1ms_ctrl);

    while (1)
    {
        U8 key_event_display = key_get_event();
        U8 pressed_keys_display = key_get_pressed();

        if(key_event_display != 0U)
        {
            show_3digits(0, key_event_display);          /* top row    */
            show_3digits(3, pressed_keys_display);          /* bottom row */
        }

        if(key_event_display != 0U)
        {
            if(pressed_keys_display == SET_KEY)
            {
                relay_on(RELAY_1);
            }
            else if(pressed_keys_display == PRG_KEY)
            {
                relay_on(RELAY_2);
            }
            else if(pressed_keys_display == RST_KEY)
            {
                relay_off(RELAY_1);
                relay_off(RELAY_2);
            }
        }

    }
}

