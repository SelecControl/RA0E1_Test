void tau_1ms_callback(timer_callback_args_t *p_args)
{
    FSP_PARAMETER_NOT_USED(p_args); // p_args usually tells why that interrupt was called and FSP_PARAMETER_NOT_USED just tells that we need to ignore this thing as we are internally calling it again and again.
    key_sample(display_active_digit());   /* 1. read key for the CC that was ON for 1 ms */
    display_scan();  /* 2. then move to the next digit */
    din_1ms();                                          /* NEW: poll RESET */
    tmr_1ms();                                          /* NEW: timer engine */
}

void start_irq_callback(external_irq_callback_args_t *p_args)
{
    FSP_PARAMETER_NOT_USED(p_args);
    din_start_edge();                                   /* one call per falling edge on START */
}
